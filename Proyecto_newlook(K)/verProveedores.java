    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String valorBusqueda = jTextField1.getText().trim();
        
        if (valorBusqueda.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Por favor ingrese un valor para buscar", 
                "Error", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        modelo.Producto producto = productoControl.obtenerProducto(valorBusqueda, "id");
        
        if (producto == null) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Producto no encontrado", 
                "Error", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        
        
        jTextArea1.setText("Lista de proveedores de producto: ");
        label2.setText(producto.nombre);
        label3.setText(producto.id);
        
        for(int i = 0; i < producto.proveedores.size(); i++){
            jTextArea1.append("\n"+producto.proveedores.get(i) + "\n");
        }
       
    }//GEN-LAST:event_jButton1ActionPerformed

