    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String proveedor = jTextField2.getText().trim();
        
        String id = label3.getText();
        
        if (proveedor.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Por favor ingrese un proveedor a añadir", 
                "Error", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        
        modelo.Producto producto = productoControl.obtenerProducto(id, "id");
        
        producto.proveedores.add(proveedor);
        

        jTextArea1.setText("Lista de proveedores de producto: ");
        label2.setText(producto.nombre);
        label3.setText(producto.id);
        
        
        for(int i = 0; i < producto.proveedores.size(); i++){
            jTextArea1.append(producto.proveedores.get(i) + "\n");
        }


        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

