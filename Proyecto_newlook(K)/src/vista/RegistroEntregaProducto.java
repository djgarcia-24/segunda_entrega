    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String productoNombre = (String) jComboBoxProducto.getSelectedItem();
        String cantidadStr = jTextCantidad.getText().trim();
        String fechaEntregaStr = jTextFechaEntrega.getText().trim();
        String fechaVencimientoStr = vencimiento_txt.getText().trim();
        
        
        
        
        
        
        
        if (productoNombre == null || productoNombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                javax.swing.SwingUtilities.getWindowAncestor(this),
                "Por favor seleccione un producto", 
                "Validación", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        
        if (cantidadStr.isEmpty() || fechaEntregaStr.isEmpty() ) {
            javax.swing.JOptionPane.showMessageDialog(
                javax.swing.SwingUtilities.getWindowAncestor(this),
                "Por favor complete todos los campos", 
                "Validación", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        try {
            int cantidad = Integer.parseInt(cantidadStr);
            
            if (cantidad <= 0) {
                javax.swing.JOptionPane.showMessageDialog(
                    javax.swing.SwingUtilities.getWindowAncestor(this),
                    "La cantidad debe ser mayor a 0", 
                    "Validación", 
                    javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }
            
            java.time.LocalDate fechaEntrega = java.time.LocalDate.parse(fechaEntregaStr);
            
            
            java.time.LocalDate fechaVencimiento= null;
            
            if(fechaVencimientoStr.isEmpty() ){
                fechaVencimiento = null;
            }
            else{
                fechaVencimiento = java.time.LocalDate.parse(fechaVencimientoStr);
            }
            
            
            boolean resultado = productoControl.registrarEntrega(productoNombre, cantidad, fechaEntrega, fechaVencimiento);
         
            
        if(resultado){
            JOptionPane.showMessageDialog(
                javax.swing.SwingUtilities.getWindowAncestor(this),
                "Entrega registrada", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            jTextCantidad.setText("");
            jTextFechaEntrega.setText("");
            vencimiento_txt.setText("");
            mostrarInfoProducto();
        }
        else{
            JOptionPane.showMessageDialog(
                javax.swing.SwingUtilities.getWindowAncestor(this),
                "Producto no encontrado", "Error", JOptionPane.ERROR_MESSAGE);

        }
            
            
            
  
            
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(
                javax.swing.SwingUtilities.getWindowAncestor(this),
                "La cantidad debe ser un número válido", 
                "Validación", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
        } catch (java.time.format.DateTimeParseException e) {
            javax.swing.JOptionPane.showMessageDialog(
                javax.swing.SwingUtilities.getWindowAncestor(this),
                "Las fechas deben estar en formato yyyy-MM-dd (ejemplo: 2025-12-31) o dejar en blanco en caso de no vencer", 
                "Validación", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

