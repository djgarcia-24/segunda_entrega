    private void cargarProductos() {
        jComboBoxProducto.removeAllItems();
        for (modelo.Producto p : productoControl.obtenerTodosProductos()) {
            jComboBoxProducto.addItem(p.getNombre());
        }
    }
    
    private void mostrarInfoProducto() {
        String productoNombre = (String) jComboBoxProducto.getSelectedItem();
        if (productoNombre != null && !productoNombre.isEmpty()) {
            modelo.Producto producto = productoControl.obtenerProducto(productoNombre, "nombre");
            if (producto != null) {
                producto_display.setText(producto.getNombre());
                categoria.setText(producto.getCategoria());
                cantidad.setText(Integer.toString(producto.getCantidad_total()));
                id_value.setText(producto.getId());
                if(producto.entregas.get(0).vencimiento == null){
                    vencimiento_txt.setEditable(false);
                }
                else{
                    vencimiento_txt.setEditable(true);
                }
                
                
                
            }
            
            
            
        }
    }

